function fetchText(url) {
  return new Promise((resolve, reject) => {
    https
      .get(
        url,
        {
          headers: {
            'user-agent': 'CinemaCatalogPathFetcher/1.1',
            'accept-language': 'en-US,en;q=0.9',
          },
        },
        (res) => {
          if (res.statusCode === 301 || res.statusCode === 302) {
            const loc = res.headers.location
            if (!loc) {
              reject(new Error('Redirect without location'))
              return
            }
            const next = loc.startsWith('http') ? loc : new URL(loc, url).href
            res.resume()
            resolve(fetchText(next))
            return
          }
          let data = ''
          res.on('data', (c) => (data += c))
          res.on('end', () => resolve(data))
        },
      )
      .on('error', reject)
  })
}

function firstFile(html, re) {
  const m = html.match(re)
  return m ? `/${m[1]}` : null
}

function firstBackdropFromBackdropsPage(html) {
  const marker = 'id="image_menu"'
  let slice = html
  const i = html.indexOf(marker)
  if (i !== -1) slice = html.slice(i)
  const re = /image\.tmdb\.org\/t\/p\/original\/([A-Za-z0-9_.-]+\.jpg)/g
  let m
  while ((m = re.exec(slice)) !== null) {
    return `/${m[1]}`
  }
  return null
}

async function pathsForTmdbId(tmdbId) {
  const main = await fetchText(`https://www.themoviedb.org/movie/${tmdbId}`)
  const poster =
    firstFile(main, /image\.tmdb\.org\/t\/p\/w500\/([A-Za-z0-9_.-]+\.jpg)/) ??
    firstFile(main, /image\.tmdb\.org\/t\/p\/w440_and_h660_face\/([A-Za-z0-9_.-]+\.jpg)/)

  let backdrop = null
  try {
    const backs = await fetchText(
      `https://www.themoviedb.org/movie/${tmdbId}/images/backdrops`,
    )
    backdrop = firstBackdropFromBackdropsPage(backs)
  } catch {
    backdrop = null
  }

  return { poster, backdrop }
}

const FALLBACK_POSTER = '/8b8R8l88Qje9dn9OE8PY05Nxl1X.jpg'
const FALLBACK_BACKDROP = '/xOMo8BRK7PfcJv9JCnx7s5hj0PX.jpg'

async function main() {
  const out = {}
  for (const [cid, mid] of MAP) {
    try {
      const { poster, backdrop } = await pathsForTmdbId(mid)
      out[cid] = [poster ?? FALLBACK_POSTER, backdrop ?? FALLBACK_BACKDROP]
      if (!poster || !backdrop) {
        console.warn(`Fallback used for ${cid} (TMDB ${mid})`, { poster, backdrop })
      }
      process.stdout.write('.')
      await new Promise((r) => setTimeout(r, 400))
    } catch (e) {
      console.error(`Fail ${cid} TMDB ${mid}`, e.message)
      out[cid] = [FALLBACK_POSTER, FALLBACK_BACKDROP]
    }
  }
  console.log('\nWriting catalog-tmdb-paths.mjs …')
  const body = `/**\n * Auto-generated by scripts/scrape-tmdb-catalog-paths.mjs\n * TMDB CDN file paths only (leading slash).\n */\nexport const TMDB_PATHS = ${JSON.stringify(out, null, 2)}\n`
  writeFileSync(join(__dirname, 'catalog-tmdb-paths.mjs'), body)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
